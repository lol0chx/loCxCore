package com.loCxCore.dto;

public class DrinkRequest {
    private String name;
    private String size;

    public DrinkRequest() {
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getSize() {
        return size;
    }

    public void setSize(String size) {
        this.size = size;
    }
}
